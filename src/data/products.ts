/* --------------------------------------------------------------- Queries */

export function getProductBySlug(slug: string) {
  return products.find((p) => p.slug === slug);
}

export function getProductById(id: string) {
  return products.find((p) => p.id === id);
}

export function getProductsByCategory(category: CategorySlug) {
  return products.filter((p) => p.category === category);
}

export function getProductsByTag(tag: ProductTag, limit?: number) {
  const list = products.filter((p) => p.tags.includes(tag));
  return limit ? list.slice(0, limit) : list;
}

export function getRelatedProducts(product: Product, limit = 4) {
  const sameCategory = products.filter((p) => p.category === product.category && p.id !== product.id);
  const sameType = sameCategory.filter((p) => p.type === product.type);
  const rest = sameCategory.filter((p) => p.type !== product.type);
  return [...sameType, ...rest].slice(0, limit);
}

export function searchProducts(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return products;
  return products.filter((p) =>
    [p.name, p.type, p.subtitle, p.category].some((field) => field.toLowerCase().includes(q)),
  );
}
